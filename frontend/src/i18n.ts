export function useI18n() {
  const { lang, setLang, toggleLang } = useLanguageStore();
  const dict = translations[lang];

  const t = (key: keyof typeof translations.es, params?: Record<string, string | number>): string => {
    let text = dict[key] || translations.es[key] || (key as string);
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        text = text.replace(`{${k}}`, String(v));
      });
    }
    return text;
  };

  return { t, lang, setLang, toggleLang };
}
